// Validate the 26 authored exercises before they are inserted, and emit the SQL.
//
// These are the movements a glute-focused business had ZERO of: clamshells, frog pumps, curtsy
// lunges, Bulgarian split squats, hip thrust variants. They are member-facing coaching text in two
// languages, so they get checked the way member-facing copy gets checked, not the way seed data does.
//
// Usage: node .qa-visual/exercise-additions-check.mjs <items.json> [--sql out.sql]
import fs from 'node:fs';

const src = process.argv[2];
if (!src) {
  console.log('usage: node .qa-visual/exercise-additions-check.mjs <items.json> [--sql out.sql]');
  process.exit(1);
}
const items = JSON.parse(fs.readFileSync(src, 'utf8'));

const EXPECTED = 26;
const MUSCLES = new Set(['glutes', 'abductors', 'hamstrings', 'quadriceps']);
const EQUIP = new Set(['dumbbell', 'bands', 'body only', 'cable', 'machine']);
const DIFF = new Set(['beginner', 'intermediate']);

// Spanish words that are actually English left behind. The intro message shipped "150 to 134 lb"
// mid-Spanish earlier today, so this is a known failure mode for bilingual copy, not a hypothetical.
const ENGLISH_LEAK = /\b(the|your|and|with|keep|squeeze|hips|knees|foot|feet|back|down|up|drive|hold|slow)\b/i;

const fails = [];
const seen = new Set();

for (const it of items) {
  const n = it.name_en ?? '(unnamed)';
  const both = `${it.cues_en ?? ''} ${it.cues_es ?? ''} ${it.name_en ?? ''} ${it.name_es ?? ''}`;

  if (seen.has(n)) fails.push(`${n}: duplicate`);
  seen.add(n);

  for (const f of ['name_en', 'name_es', 'cues_en', 'cues_es', 'muscle_group', 'equipment', 'difficulty']) {
    if (!String(it[f] ?? '').trim()) fails.push(`${n}: ${f} empty`);
  }
  if (!MUSCLES.has(it.muscle_group)) fails.push(`${n}: bad muscle_group "${it.muscle_group}"`);
  if (!EQUIP.has(it.equipment)) fails.push(`${n}: bad equipment "${it.equipment}"`);
  if (!DIFF.has(it.difficulty)) fails.push(`${n}: bad difficulty "${it.difficulty}"`);

  // Brand rules.
  if (/—/.test(both)) fails.push(`${n}: em dash`);
  if (/\bAI\b|\bI\.A\.\b/.test(both)) fails.push(`${n}: says AI`);

  // Spanish must be Spanish. name_es being identical to name_en means it was not translated at all,
  // which is the exact defect 25 of the existing rows already have.
  if ((it.name_es ?? '').trim().toLowerCase() === (it.name_en ?? '').trim().toLowerCase()) {
    fails.push(`${n}: name_es is a copy of name_en`);
  }
  if (ENGLISH_LEAK.test(it.cues_es ?? '')) {
    const hit = (it.cues_es.match(ENGLISH_LEAK) || [])[0];
    fails.push(`${n}: English word "${hit}" left in cues_es`);
  }

  // Read on a phone between sets. Long enough to coach, short enough to read.
  const words = (it.cues_en ?? '').split(/\s+/).length;
  if (words < 25) fails.push(`${n}: cues_en too thin (${words} words)`);
  if (words > 160) fails.push(`${n}: cues_en too long to read mid-set (${words} words)`);
}

if (items.length !== EXPECTED) fails.push(`expected ${EXPECTED} items, got ${items.length}`);

// The whole point of the exercise. If the glute count is not what we set out to add, something got
// dropped between the research and the write.
const glutes = items.filter((i) => i.muscle_group === 'glutes').length;
const abductors = items.filter((i) => i.muscle_group === 'abductors').length;
if (glutes < 10) fails.push(`only ${glutes} glute movements, expected at least 10`);
if (abductors < 5) fails.push(`only ${abductors} abduction movements, expected at least 5`);

console.log(`${items.length} items: ${glutes} glutes, ${abductors} abductors, ` +
  `${items.filter((i) => i.equipment === 'bands').length} band, ` +
  `${items.filter((i) => i.equipment === 'body only').length} bodyweight, ` +
  `${items.filter((i) => i.equipment === 'dumbbell').length} dumbbell`);

if (fails.length) {
  console.log('\nFAILED:');
  for (const f of fails) console.log('  -', f);
  process.exit(1);
}
console.log('PASS: all checks clean.');

// --- emit SQL ------------------------------------------------------------------------------------
const sqlFlag = process.argv.indexOf('--sql');
if (sqlFlag > -1 && process.argv[sqlFlag + 1]) {
  const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
  const rows = items.map((i) => {
    // Everything that is not primarily glutes still trains them here: that is why these movements
    // were chosen. Tagging it makes them answer a glute filter, which is the whole point of 0105.
    const secondary = i.muscle_group === 'glutes' ? `'{}'` : `'{glutes}'`;
    return `  (null, ${q(i.name_en)}, ${q(i.name_es)}, ${q(i.cues_en)}, ${q(i.cues_es)}, ` +
      `${q(i.muscle_group)}, ${q(i.equipment)}, ${q(i.difficulty)}, 'strength', true, ${secondary})`;
  });
  const sql = `-- Generated by .qa-visual/exercise-additions-check.mjs. Do not hand-edit.
insert into public.exercises
  (company_id, name_en, name_es, cues_en, cues_es, muscle_group, equipment, difficulty, category, is_core, secondary_muscles)
values
${rows.join(',\n')}
on conflict do nothing;
`;
  fs.writeFileSync(process.argv[sqlFlag + 1], sql);
  console.log(`\nSQL written: ${process.argv[sqlFlag + 1]} (${rows.length} rows)`);
}
